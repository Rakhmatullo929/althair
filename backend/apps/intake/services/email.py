# Simple email validation (not RFC-complete, good enough for form parsing)
_EMAIL_RE = re.compile(r'^[^@\s]+@[^@\s]+\.[^@\s]+$')

# Loose email / phone scanners used as a last-resort body sweep when neither
# the regex parser nor the LLM surfaced a requester identifier — people
# routinely drop their contact details in prose ("reach me at maria@ ...").
_LOOSE_EMAIL_RE = re.compile(r'\b[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}\b')
_LOOSE_PHONE_RE = re.compile(
    r'(?:(?<!\d)\+?1[\s.\-])?\(?\d{3}\)?[\s.\-]?\d{3}[\s.\-]?\d{4}(?!\d)'
)


def _first_body_email(body: str, *, exclude: set[str] | None = None) -> str:
    """Return the first email address found in ``body`` that's not in ``exclude``."""
    if not body:
        return ''
    exclude = {(e or '').lower() for e in (exclude or set())}
    for m in _LOOSE_EMAIL_RE.finditer(body):
        candidate = m.group(0).strip().lower()
        if not candidate:
            continue
        # Skip obvious no-reply / mailbox relay addresses.
        local = candidate.split('@', 1)[0]
        if local in {'noreply', 'no-reply', 'donotreply', 'do-not-reply',
                     'mailer-daemon', 'postmaster', 'notifications'}:
            continue
        if candidate in exclude:
            continue
        return candidate
    return ''


def _first_body_phone(body: str) -> str:
    """Return the first North-American-looking phone number in ``body`` (or '')."""
    if not body:
        return ''
    m = _LOOSE_PHONE_RE.search(body)
    return m.group(0).strip() if m else ''


def _strip_html(html: str) -> str:
    text = re.sub(
        r'<(style|script)[^>]*>.*?</(style|script)>',
        '', html, flags=re.IGNORECASE | re.DOTALL,
    )
    text = re.sub(r'<(?:br|p|div|tr|li|h\d)[^>]*>', '\n', text, flags=re.IGNORECASE)
    text = re.sub(r'<[^>]+>', '', text)
    for entity, char in (
            ('&nbsp;', ' '), ('&amp;', '&'), ('&lt;', '<'),
            ('&gt;', '>'), ('&quot;', '"'), ('&#39;', "'"),
            ('&#13;', ''), ('&#10;', '\n'),
    ):
        text = text.replace(entity, char)
    text = re.sub(r'[ \t]+', ' ', text)
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text.strip()


# Some upstream relays (Power Automate, certain Outlook → JSON connectors,
# webhook bridges that JSON-encode the body twice) deliver the email body with
# *literal* backslash-r / backslash-n sequences instead of real newlines —
# i.e. the four characters "\", "r", "\", "n" appear inline rather than CR/LF.
# `str.splitlines()` does not split on those, so the line-oriented parser
# grabs the entire rest of the body into the first matched field
# ("Lot / phase: Lots 14 through 22\r\nAddress: ...\r\nCity / state: ...").
# Normalize them back to real newlines before any other processing.
_LITERAL_NEWLINE_RE = re.compile(r'\\r\\n|\\n|\\r')


def _normalize_literal_newlines(text: str) -> str:
    if not text or '\\' not in text:
        return text
    return _LITERAL_NEWLINE_RE.sub('\n', text)


# JSON-envelope leak detector.  Matches the canonical key separator
# `","keyname":` that JSON encoders produce between fields.  Each `"` /
# `,` may be preceded by an optional backslash so both the decoded form
# (Power Automate / Outlook → webhook delivers the body already
# JSON-decoded) and the doubly-encoded form (`\",\"keyname\":`) are
# caught by the same regex.  Used per-line by the body parser below to
# chop garbage that some flows leak into the email body field.
_JSON_TAIL_LEAK_RE = re.compile(r'\\?"\\?,\\?"\\?[A-Za-z_]\w*\\?":')


# Bullet / list prefixes we silently strip at the start of each line
# (•, ·, ▪, ●, ○, ◦, ·, →, plain dash/asterisk, and common numeric list markers).
_BULLET_PREFIX_RE = re.compile(
    r'^[\s\u00a0]*'                              # leading whitespace / NBSP
    r'(?:[\u2022\u2023\u2043\u25aa\u25cf\u25cb\u25e6\u00b7\*\-\u2192]|'  # glyph bullets
    r'\d{1,2}[.)])'                             # "1." / "1)" style numbering
    r'[\s\u00a0]+'
)


# ── Single-line labelled form pre-splitter ────────────────────────────────────
# Some contact-form relays (and mobile mail clients that strip newlines) flatten
# a multi-field form submission onto a single line:
#
#   "Name: Mike Torres Phone: 412-555-0193 Email: mike@... Message: I need …"
#
# The line-oriented parser below only matches labels at the start of a line, so
# on flattened input it would greedily capture the whole rest of the line into
# the first matched field (usually `requester_name`) and miss everything else.
#
# To fix that without rewriting the parser, we insert a newline in front of
# every KNOWN label that appears mid-line.  The behaviour is conservative:
#
#   • only fires when the input has no newlines (already multi-line → no-op);
#   • only fires when ≥ 2 distinct known labels appear;
#   • only matches labels that are preceded by whitespace or punctuation
#     and followed by ":" or "-", so a casual sentence like "Call me on
#     my phone today" is untouched (no colon after "phone").
#
