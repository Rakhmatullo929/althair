# One pre-compiled regex used by both `_explode_single_line_labels` and tests.
# Longest labels are ordered first so e.g. "property address" wins over plain
# "address".  Escaped, joined with `|`, wrapped as a named capture group.
#
# After the colon/dash we accept either whitespace (`\s`) OR end-of-string
# (`$`).  The end-of-string branch is what handles Outlook-wrapped bodies
# where a label sits at the end of one line and its value begins on the
# next — e.g.
#     "Lot / phase: Lots 14-22, City / state:\nPittsburgh, PA"
# Without the `$` branch the regex couldn't see "City / state:" as a label
# (no whitespace after the colon on that line), so the line-based parser
# greedily merged "City / state:" into the preceding field's value.
_INLINE_LABEL_RE = re.compile(
    r'(?:(?<=^)|(?<=[\s.,;()]))'
    r'(?P<label>(?:' + '|'.join(
        re.escape(t) for t in
        sorted(set(_INLINE_LABEL_TOKENS), key=len, reverse=True)
    ) + r'))'
    r'\s*[:\-](?=\s|$)',
    re.IGNORECASE,
)


def _explode_line_labels(line: str) -> list[str]:
    """Split a single physical line into one chunk per labelled field.

    Returns a list of substrings, each starting at a known label token.
    Returns ``[line]`` (1-element list) when the line contains fewer than
    two labels, so callers can treat the result uniformly.

    Example
    ───────
        "Name: Mike Phone: 412-... Email: mike@..."
      → ["Name: Mike", "Phone: 412-...", "Email: mike@..."]
    """
    matches = list(_INLINE_LABEL_RE.finditer(line))
    if len(matches) < 2:
        return [line]

    pieces: list[str] = []
    first_start = matches[0].start('label')
    if first_start > 0:
        head = line[:first_start].rstrip()
        if head:
            pieces.append(head)
    for i, m in enumerate(matches):
        start = m.start('label')
        end = matches[i + 1].start('label') if i + 1 < len(matches) else len(line)
        chunk = line[start:end].rstrip()
        if chunk:
            pieces.append(chunk)
    return pieces if len(pieces) >= 2 else [line]


def _explode_single_line_labels(text: str) -> str:
    """Per-line label exploder.

    Earlier the function only fired when the *entire* message was a single
    physical line (no \\n anywhere).  That left a bug class wide open: when
    Power Automate / Outlook adds even a single stray newline (header,
    trailing blank line, embedded signature) but the actual form body still
    sits on one long line, the explode was skipped entirely and the
    line-oriented parser captured everything into the first matched label
    (typical victim: ``requester_name`` swallows the whole flat string).

    Applying the explode per-line fixes that case while remaining a no-op
    for already-properly-formatted multi-line bodies.
    """
    if not text:
        return text

    out_lines: list[str] = []
    for line in text.splitlines():
        out_lines.extend(_explode_line_labels(line))
    return '\n'.join(out_lines)


def _parse_body_fields(body: str) -> Dict[str, str]:
    if not body:
        return {}

    text = _strip_html(body) if re.search(r'<[a-zA-Z]', body) else body
    # Some relays deliver bodies with literal "\r\n" text instead of real
    # newlines — convert them so splitlines() works correctly below.
    text = _normalize_literal_newlines(text)
    # Handle flattened single-line forms before the line-oriented parser runs.
    text = _explode_single_line_labels(text)

    extracted: Dict[str, str] = {}

    for line in text.splitlines():
        # Strip leading bullet / list markers so that "• Requester Name: …"
        # matches the same regexes as "Requester Name: …".
        line = _BULLET_PREFIX_RE.sub('', line).strip()
        # Truncate at the first JSON-envelope leak.  Power Automate /
        # Outlook → JSON connectors sometimes leak the envelope object
        # into a single line of the body, leaving a tail like:
        #   Service Type: Site Cleanup","importance":"normal","conversationId":"…
        # The literal sequence `","<json-key>":` (and its backslash-
        # escaped twin) never appears in a real email body — anything
        # from there onwards is garbage.  We cut per-line (NOT body-wide)
        # so a JSON leak on one field doesn't wipe out subsequent
        # legitimate fields that come after on later lines.
        m = _JSON_TAIL_LEAK_RE.search(line)
        if m:
            line = line[:m.start()].rstrip(' \t\r\n",')
        # Strip a trailing field-separator comma/semicolon left behind by the
        # single-line exploder so per-field regexes whose value char-classes
        # don't include "," (e.g. phone, email) still match.  We never strip
        # commas mid-string, so "Pittsburgh, PA" is unaffected.
        line = re.sub(r'[\s,;]+$', '', line)
        if not line:
            continue

        for field_name, patterns in _LABEL_PATTERNS.items():
            if field_name in extracted:
                continue
            for pattern in patterns:
                m = re.match(pattern, line, re.IGNORECASE)
                if m:
                    # Strip surrounding whitespace/quotes AND a single trailing
                    # comma/semicolon so flat comma-separated forms
                    # ("Community: Ridgeview Estates, Lot / phase: ...") don't
                    # leave a stray "," at the end of every value.  We don't
                    # strip commas anywhere else — "Pittsburgh, PA" must keep
                    # the comma between city and state.
                    value = m.group(1).strip(' \t\r\n"\'')
                    value = re.sub(r'[\s,;]+$', '', value)
                    if value:
                        extracted[field_name] = value
                    break

    # ── Natural-language fallback on the whole body ──────────────────────────
    # These heuristics pick up fields that customers mention in prose without
    # explicit labels — e.g. "in lot #42 of the ABC Homes development".
    # We only fill fields that weren't already matched by labelled regexes.
    for field_name, value in _extract_freeform_fields(text).items():
        if field_name not in extracted and value:
            extracted[field_name] = value

    return extracted


# ── Natural-language field extraction (no labels required) ───────────────────
# These patterns scan the full body (not line-by-line) to catch field values
# that customers mention in prose, e.g.:
#
#   "I need street cleaning in lot #42 of the ABC Homes development this week."
#
# We keep them *conservative*: each pattern only fires when it sees a clear
# contextual anchor (a known "company-suffix" word such as Homes / Builders /
# Development / Community, or the word "Lot" / "Unit" before a number).

# Suffix words that are part of a *company* name ("ABC Homes" — "Homes" stays
# in the builder field).
_COMPANY_SUFFIX = (
    r'(?:homes|builders?|construction|group|realty|properties|'
    r'residences|llc|inc|incorporated|corp(?:oration)?|co\.?)'
)

# Suffix words that mark a *location* type ("ABC Homes development" —
# "development" is NOT part of the builder name, but the whole phrase becomes
# the community value).
_LOCATION_SUFFIX = (
    r'(?:developments?|subdivisions?|communit(?:y|ies)|estates?|'
    r'villages?|ranch|farms?|phase)'
)

# Up to 4 capitalised tokens — "ABC", "Beacon Hill", "The Preserve at Elmwood".
